import { motion } from 'framer-motion'
import { Lightbulb, Shuffle, Wand2 } from 'lucide-react'
import { useState } from 'react'
import type { Plan } from '@soiree/shared'
import { api } from '../../lib/api'

interface Props {
  plan: Plan
  setPlan: (fn: (p: Plan) => Plan) => void
  toast: (m: string) => void
}

export default function IdeasTab({ plan, setPlan, toast }: Props) {
  const [busy, setBusy] = useState(false)
  const [extra, setExtra] = useState('')

  const run = async () => {
    setBusy(true)
    try {
      const res = await api.plans.regenerateIdeas(plan.id, extra)
      setPlan((p) => ({ ...p, ideas: res.ideas }))
      toast(res.ai ? 'Fresh ideas generated by Gemini' : 'Ideas refreshed')
    } catch {
      toast('Failed to refresh ideas')
    } finally {
      setBusy(false)
    }
  }

  return (
    <>
      <form
        className="ideas-bar"
        onSubmit={(e) => {
          e.preventDefault()
          void run()
        }}
      >
        <input
          className="input"
          aria-label="Ideas direction"
          placeholder="Steer the ideas: “more sustainable”, “for kids”, “budget-friendly”, “royal palace look”…"
          value={extra}
          onChange={(e) => setExtra(e.target.value)}
          disabled={busy}
        />
        <button className="btn btn-primary btn-sm" type="submit" disabled={busy}>
          {busy ? <Shuffle size={15} /> : <Wand2 size={15} />}
          {busy ? 'Thinking…' : 'Regenerate ideas'}
        </button>
      </form>
      <div className="idea-grid">
        {plan.ideas.map((g, i) => (
          <motion.div
            className="idea"
            key={g.title + i}
            initial={{ opacity: 0, y: 20 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ delay: i * 0.07 }}
          >
            <h4>
              <Lightbulb size={20} />
              {g.title}
            </h4>
            <ul>
              {g.items.map((it) => (
                <li key={it}>{it}</li>
              ))}
            </ul>
          </motion.div>
        ))}
      </div>
    </>
  )
}
