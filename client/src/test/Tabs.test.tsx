import { describe, it, expect, vi, beforeEach } from 'vitest'
import { render, screen, fireEvent, waitFor } from '@testing-library/react'
import type { Plan } from '@soiree/shared'
import TimelineTab from '../components/tabs/TimelineTab.js'
import IdeasTab from '../components/tabs/IdeasTab.js'
import MoodboardTab from '../components/tabs/MoodboardTab.js'
import AskTab from '../components/tabs/AskTab.js'
import VendorsTab from '../components/tabs/VendorsTab.js'
import { api } from '../lib/api.js'

describe('Tabs Component Suite: Timeline, Ideas, Moodboard, Ask, Vendors', () => {
  const samplePlan: Plan = {
    id: 'tab-plan-1',
    createdAt: 1774900000000,
    brief: {
      title: 'Emerald Gala',
      type: 'birthday',
      date: '2026-10-30',
      guests: 50,
      budget: 5000,
      currency: 'EUR',
      city: 'Vienna',
      vibe: 'Opulent',
      notes: '',
    },
    summary: 'A luxurious autumn dinner in Vienna.',
    generatedBy: 'local',
    budget: [{ id: 'b1', category: 'Catering', allocated: 2500, spent: 1000, note: '' }],
    timeline: [
      { id: 'm1', label: 'Book Venue', detail: 'Reserve grand hall', weeksBefore: 8, done: false },
      { id: 'm2', label: 'Send Invitations', detail: 'Digital cards', weeksBefore: 4, done: true },
      { id: 'm3', label: 'Final Walkthrough', detail: 'Venue check', weeksBefore: 0, done: false },
    ],

    vendors: [
      { id: 'v1', category: 'Caterer', name: 'Gourmet Co', status: 'todo', estimate: 2000, tips: 'Ask tasting' },
    ],
    ideas: [{ title: 'Theme Concepts', items: ['Gilded Tableware', 'Live String Quartet'] }],
  }

  beforeEach(() => {
    vi.restoreAllMocks()
  })

  it('renders TimelineTab and invokes milestone status toggle', () => {
    const toggleMilestone = vi.fn().mockResolvedValue(undefined)
    render(<TimelineTab plan={samplePlan} toggleMilestone={toggleMilestone} />)

    expect(screen.getByText('Book Venue')).toBeInTheDocument()
    expect(screen.getByText('Send Invitations')).toBeInTheDocument()

    const checkButtons = screen.getAllByRole('button', { name: /mark as/i })
    fireEvent.click(checkButtons[0]!)
    expect(toggleMilestone).toHaveBeenCalledWith('m1')
  })

  it('renders IdeasTab, displays items, and regenerates ideas', async () => {
    const setPlan = vi.fn()
    const toast = vi.fn()
    vi.spyOn(api.plans, 'regenerateIdeas').mockResolvedValue({
      ideas: [{ title: 'Botanical Decor', items: ['Hanging ferns'] }],
      ai: true,
    })

    render(<IdeasTab plan={samplePlan} setPlan={setPlan} toast={toast} />)
    expect(screen.getByText('Theme Concepts')).toBeInTheDocument()
    expect(screen.getByText('Gilded Tableware')).toBeInTheDocument()

    const input = screen.getByLabelText('Ideas direction')
    fireEvent.change(input, { target: { value: 'Eco-friendly chic' } })

    const submitBtn = screen.getByRole('button', { name: /generate/i })
    fireEvent.click(submitBtn)

    await waitFor(() => {
      expect(api.plans.regenerateIdeas).toHaveBeenCalledWith('tab-plan-1', 'Eco-friendly chic')
      expect(setPlan).toHaveBeenCalled()
      expect(toast).toHaveBeenCalledWith('Fresh ideas generated by Gemini')
    })
  })

  it('renders MoodboardTab, displays swatches, copies hex, and regenerates', async () => {
    const toast = vi.fn()
    const mockMb = {
      moodboard: {
        palette: [
          { hex: '#1b4332', name: 'Forest Jade', role: 'Primary' },
          { hex: '#d8f3dc', name: 'Soft Sage', role: 'Accent' },
        ],
        typography: {
          heading: 'Cormorant Garamond',
          body: 'Inter',
          vibe: 'Editorial Luxury',
        },
        motifs: ['Lotus', 'Gilded arches'],
        decor: ['Silk runners', 'Brass candelabras'],
        outfitNotes: ['Black tie optional'],
        playlistVibes: ['Acoustic jazz', 'Neo-classical'],
      },
      generatedBy: 'gemini' as const,
      createdAt: '2026-01-01',
    }

    vi.spyOn(api.plans, 'getMoodboard').mockResolvedValue(mockMb)
    vi.spyOn(api.plans, 'generateMoodboard').mockResolvedValue(mockMb)

    render(<MoodboardTab plan={samplePlan} toast={toast} />)
    await waitFor(() => {
      expect(screen.getByText('Cormorant Garamond')).toBeInTheDocument()
      expect(screen.getByText('Forest Jade')).toBeInTheDocument()
    })

    // Click swatch to copy hex
    const swatch = screen.getByLabelText(/Copy hex code for Forest Jade/i)
    fireEvent.click(swatch)
    expect(toast).toHaveBeenCalledWith('Copied #1b4332 (Forest Jade) to clipboard!')

    // Regenerate vision
    const steerInput = screen.getByLabelText('Steer moodboard vision')
    fireEvent.change(steerInput, { target: { value: 'Twilight violet' } })
    const regenBtn = screen.getByRole('button', { name: /regenerate/i })
    fireEvent.click(regenBtn)
    await waitFor(() => {
      expect(api.plans.generateMoodboard).toHaveBeenCalledWith('tab-plan-1', 'Twilight violet')
    })
  })

  it('renders MoodboardTab empty state and triggers first generation', async () => {
    const toast = vi.fn()
    const notFoundErr = new Error('Not found') as Error & { status: number }
    notFoundErr.status = 404
    vi.spyOn(api.plans, 'getMoodboard').mockRejectedValue(notFoundErr)
    vi.spyOn(api.plans, 'generateMoodboard').mockResolvedValue({
      moodboard: {
        palette: [{ hex: '#112233', name: 'Navy', role: 'Base' }],
        typography: { heading: 'Inter', body: 'Inter', vibe: 'Minimal' },
        motifs: [],
        decor: [],
        outfitNotes: [],
        playlistVibes: [],
      },
      generatedBy: 'offline',
      createdAt: '2026-01-01',
    })

    render(<MoodboardTab plan={samplePlan} toast={toast} />)
    await waitFor(() => {
      expect(screen.getByText('No Moodboard Generated Yet')).toBeInTheDocument()
    })

    const genBtn = screen.getByRole('button', { name: /generate moodboard/i })
    fireEvent.click(genBtn)
    await waitFor(() => {
      expect(api.plans.generateMoodboard).toHaveBeenCalledWith('tab-plan-1', undefined)
    })
  })

  it('renders AskTab and handles question submission with reply', async () => {
    vi.spyOn(api.plans, 'getChat').mockResolvedValue({ messages: [] })
    vi.spyOn(api.plans, 'sendChat').mockResolvedValue({
      userMessage: { role: 'user', text: 'What cocktails fit?' },
      reply: { role: 'assistant', text: 'A French 75 or Kir Royale.' },
      ai: true,
    })

    render(<AskTab plan={samplePlan} />)
    const input = screen.getByLabelText('Ask Soirée')
    fireEvent.change(input, { target: { value: 'What cocktails fit?' } })

    const sendBtn = screen.getByRole('button', { name: /send/i })
    fireEvent.click(sendBtn)

    await waitFor(() => {
      expect(screen.getByText('A French 75 or Kir Royale.')).toBeInTheDocument()
    })
  })

  it('renders VendorsTab, adds vendor, removes vendor, and handles empty state', async () => {
    const setPlan = vi.fn()
    const toast = vi.fn()
    vi.spyOn(api.plans, 'addVendor').mockResolvedValue({
      vendor: { id: 'v2', category: 'Florist', name: 'Bloom', status: 'todo', estimate: 800, tips: '' },
    })
    vi.spyOn(api.plans, 'deleteVendor').mockResolvedValue({ message: 'Deleted' })

    const { rerender } = render(<VendorsTab plan={samplePlan} setPlan={setPlan} toast={toast} />)

    expect(screen.getByText('Caterer')).toBeInTheDocument()
    const statusBtn = screen.getByTitle('Click to toggle status')
    fireEvent.click(statusBtn)

    const nameInput = screen.getByLabelText('Caterer vendor name')
    fireEvent.change(nameInput, { target: { value: 'Imperial Kitchens' } })
    expect(setPlan).toHaveBeenCalled()

    // Add a new vendor
    const addInput = screen.getByLabelText('New vendor category')
    fireEvent.change(addInput, { target: { value: 'Florist' } })
    const addBtn = screen.getByRole('button', { name: /add vendor/i })
    fireEvent.click(addBtn)

    await waitFor(() => {
      expect(api.plans.addVendor).toHaveBeenCalledWith('tab-plan-1', { category: 'Florist' })
    })

    // Remove vendor
    const removeBtn = screen.getByLabelText('Remove Caterer')
    fireEvent.click(removeBtn)
    await waitFor(() => {
      expect(api.plans.deleteVendor).toHaveBeenCalledWith('tab-plan-1', 'v1')
    })

    // Empty state
    rerender(<VendorsTab plan={{ ...samplePlan, vendors: [] }} setPlan={setPlan} toast={toast} />)
    expect(screen.getByText('No vendors added yet')).toBeInTheDocument()
  })
})
